const fs = require('fs');
const path = require('path');

const NOTES_DIR = path.join(__dirname, '../static/data/meetings/notes');
const OUTPUT_FILE = path.join(NOTES_DIR, 'index.ts');

function run() {
  const items = fs.readdirSync(NOTES_DIR);
  const meetings = [];

  for (const item of items) {
    const dirPath = path.join(NOTES_DIR, item);
    if (!fs.statSync(dirPath).isDirectory()) {
      continue;
    }

    const mdPath = path.join(dirPath, 'index.md');
    if (!fs.existsSync(mdPath)) {
      continue;
    }

    const content = fs.readFileSync(mdPath, 'utf8');
    const lines = content.split('\n');

    // Find the title (usually the first H1 line starting with #)
    let title = '';
    for (const line of lines) {
      if (line.startsWith('# ')) {
        title = line.substring(2).trim();
        break;
      }
    }
    if (!title) {
      title = `Podman Meeting ${item}`;
    }

    const isCabal = title.toLowerCase().includes('cabal');

    // Find human readable date from the first H2 header
    let date = '';
    for (const line of lines) {
      if (line.startsWith('## ')) {
        const h2 = line.substring(3).trim();
        date = h2.split(/[0-9]{2}:[0-9]{2}/)[0].trim();
        break;
      }
    }
    if (!date) {
      date = item; // Fallback to directory name
    }

    // Find recording link
    let videoLink = '';
    for (const line of lines) {
      if (line.includes('[Recording]')) {
        const match = line.match(/\[Recording\]\((.*?)\)/);
        if (match) {
          videoLink = match[1];
          break;
        }
      }
    }

    meetings.push({
      folderName: item,
      date,
      title,
      isCabal,
      videoLink,
    });
  }

  // Sort meetings by folderName descending (which is date descending)
  meetings.sort((a, b) => b.folderName.localeCompare(a.folderName));

  // Generate the index file content
  let output = `// Auto-generated by scripts/generate-meetings-index.js. Do not edit directly.\n`;
  output += `export interface MeetingMetadata {\n`;
  output += `  folderName: string;\n`;
  output += `  date: string;\n`;
  output += `  title: string;\n`;
  output += `  isCabal: boolean;\n`;
  output += `  videoLink: string;\n`;
  output += `  importMDX: () => Promise<any>;\n`;
  output += `}\n\n`;
  output += `export const meetings: MeetingMetadata[] = [\n`;

  for (const m of meetings) {
    output += `  {\n`;
    output += `    folderName: '${m.folderName}',\n`;
    output += `    date: ${JSON.stringify(m.date)},\n`;
    output += `    title: ${JSON.stringify(m.title)},\n`;
    output += `    isCabal: ${m.isCabal},\n`;
    output += `    videoLink: ${JSON.stringify(m.videoLink)},\n`;
    output += `    importMDX: () => import('@site/static/data/meetings/notes/${m.folderName}/index.md'),\n`;
    output += `  },\n`;
  }

  output += `];\n\n`;
  output += `export default meetings;\n`;

  fs.writeFileSync(OUTPUT_FILE, output, 'utf8');
  console.log(`Successfully generated ${OUTPUT_FILE} with ${meetings.length} meetings.`);
}

run();
